CREATE TABLE IF NOT EXISTS public.event_photo (
    photo_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id bigint NOT NULL,
    object_key character varying(255) NOT NULL,
    member_id character(10) NOT NULL,
    gmt_create timestamp with time zone NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_event_photo_event_id ON public.event_photo (event_id);
